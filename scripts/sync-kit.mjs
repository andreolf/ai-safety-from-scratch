// Pull the branding kit (Personal Branding Intern) into the repo without modifying the originals.
//   tokens.css  -> src/styles/tokens.css (verbatim)      tokens.json -> src/styles/tokens.json
//   mascot SVGs -> src/assets/mascot/<pose>.svg + src/visuals/mascot-svgs.js (string module)
//   figure PNGs -> public/kit/<name>-{1600,800}.webp
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
const KIT = process.env.KIT || '/home/box/second-brain/Agents/francesco-design-intern/assets';
const P = '2026-10-26-ai-safety-';
const ROOT = path.resolve(import.meta.dirname, '..');
const cp = (a, b) => { fs.mkdirSync(path.dirname(b), { recursive: true }); fs.copyFileSync(path.join(KIT, a), path.join(ROOT, b)); };
cp(`${P}tokens.css`, 'src/styles/tokens.css');
cp(`${P}tokens.json`, 'src/styles/tokens.json');
const svgs = {};
for (const pose of ['neutral', 'fooled', 'alarmed', 'proud']) { cp(`${P}mascot-${pose}.svg`, `src/assets/mascot/${pose}.svg`); svgs[pose] = fs.readFileSync(path.join(ROOT, `src/assets/mascot/${pose}.svg`), 'utf8'); }
fs.writeFileSync(path.join(ROOT, 'src/visuals/mascot-svgs.js'), `// GENERATED by scripts/sync-kit.mjs from the branding kit. Do not edit; re-run the script.\nexport const MASCOT = ${JSON.stringify(svgs, null, 1)};\n`);
fs.mkdirSync(path.join(ROOT, 'public/kit'), { recursive: true });
for (const f of fs.readdirSync(KIT).filter((x) => x.startsWith(`${P}figure-`) && x.endsWith('.png'))) {
  const name = f.slice(P.length, -4);
  for (const w of [1600, 800]) execFileSync('magick', [path.join(KIT, f), '-resize', `${w}x`, '-quality', '82', '-define', 'webp:method=6', path.join(ROOT, `public/kit/${name}-${w}.webp`)]);
}
console.log('kit synced:', fs.readdirSync(path.join(ROOT, 'public/kit')).join(', '));
